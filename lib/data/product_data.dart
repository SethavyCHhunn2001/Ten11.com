  static List<Product> getProductsByCategory(String category) {
    return products.where((p) => p.category == category).toList();
  }

  static List<Product> getProductsByTag(String tag) {
    return products.where((p) => p.tag.contains(tag)).toList();
  }

  static List<Product> getProductsBySubCategory(String subCategory) {
    return products.where((p) => p.subCategory == subCategory).toList();
  }

  static List<Product> getBestSellers() {
    return products.where((p) => p.isBestSeller).toList();
  }

  static List<Product> getNewArrivals() {
    final now = DateTime.now();
    return products.where((p) => p.createdAt.difference(now).inDays.abs() <= 7).toList();
  }

  static List<Product> getOnSale() {
    return products.where((p) => p.isOnSale).toList();
  }

  static List<Product> searchProducts(String query) {
    final lowerQuery = query.toLowerCase();
    return products.where((p) =>
      p.name.toLowerCase().contains(lowerQuery) ||
      p.description.toLowerCase().contains(lowerQuery) ||
      p.category.toLowerCase().contains(lowerQuery) ||
      p.tag.toLowerCase().contains(lowerQuery)
    ).toList();
  }

  static List<String> getAllCategories() {
    return ['All', 'Tops', 'Bottoms', 'Dresses', 'Accessories', 'Bags', 'Best Sellers'];
  }

  static Map<String, int> getCategoryCounts() {
    final Map<String, int> counts = {};
    for (final product in products) {
      counts[product.category] = (counts[product.category] ?? 0) + 1;
    }
    return counts;
  }
